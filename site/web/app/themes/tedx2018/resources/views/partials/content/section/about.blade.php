				About TED
				TED is a nonprofit organization devoted to “ideas worth spreading”. Started in 1984 in California as a four-day conference about Technology, Entertainment, Design, TED has broadened its scope and grown to support those world-changing ideas with multiple initiatives. At TED, the world’s leading thinkers and doers are asked to give the talk of their lives in a maximum of 18 minutes. Talks are then made available for free at TED.com.
